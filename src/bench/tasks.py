"""
Forecasting tasks with ground-truth explanations for the XAI benchmark v2 (plan §12).

Every task is standardised with training statistics (so the mean baseline is 0),
puts the forecast target in the LAST channel (TimeMachine scans channels in one
direction, so the target token must come after the drivers), and exposes

    X[split] [N, C, L], Y[split] [N, H]     split in train / val / test
    gt_cells(i)   [C, L] bool  cells that drive the explained output of test window i   (G1, G2)
    gt_feat(i)    [C] float    ground-truth Shapley value per channel for test window i  (G3)
    score_mask    [C, L] bool  cells that count when scoring attributions

The explained scalar is the mean forecast of the target over the horizon (G3: over
explain_steps(i), one step per window).

  g1         planted-dependency series of v1 (src/synthetic/gt_generator.py)
  g2a/b/c    GroupSegment-SHAP settings A/B/C, generated by the official
             scripts/synthetic_recovery_experiment.py (external/GroupSegment-SHAP);
             the binary label is turned into a regression target y = +-1 (H = 1)
  g3         SHAPformer synthetic load data with ground-truth SHAP values
             (official data.zip, converted by scripts/prepare_shapformer.py); the
             window is past (168 h) + future (168 h) with the future load set to 0
  etth1,     public data without ground truth (phase 2: faithfulness only); standard
  weather    borders (ETT 12/4/8 months, others 70/10/20), L = H = 96, target OT (last
             column), instance normalisation on as in the original models
"""

import importlib.util
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

import numpy as np
import pandas as pd

from src.synthetic.gt_generator import CHANNELS as G1_CHANNELS, REGIME, TARGET as G1_TARGET, GTConfig, GTSeries
from third_party.priorcast.dataset_loader import _compute_borders

ROOT = Path(__file__).resolve().parents[2]
GSSHAP_DIR = ROOT / "external" / "GroupSegment-SHAP"
SHAPFORMER_NPZ = ROOT / "dataset" / "external" / "shapformer" / "synthetic.npz"


@dataclass
class Task:
    name: str
    channels: list
    L: int
    H: int
    X: dict
    Y: dict
    score_mask: np.ndarray
    gt_cells: Callable | None = None
    gt_feat: Callable | None = None
    oracle_mse: dict = field(default_factory=dict)
    explain_split: str = "test"
    norm: bool = False                 # instance normalisation inside the model
    explain_steps: Callable | None = None   # horizon steps averaged into the explained scalar (default all)
    meta: dict = field(default_factory=dict)

    @property
    def target(self) -> int:
        return len(self.channels) - 1


def _standardise(X: dict, Y: dict, y_ch: int):
    mu = X["train"].mean(axis=(0, 2), keepdims=True)
    sd = X["train"].std(axis=(0, 2), keepdims=True)
    sd[sd < 1e-8] = 1.0
    Xs = {k: ((v - mu) / sd).astype(np.float32) for k, v in X.items()}
    Ys = {k: ((v - mu[0, y_ch, 0]) / sd[0, y_ch, 0]).astype(np.float32) for k, v in Y.items()}
    return Xs, Ys, mu.ravel(), sd.ravel()


# ---------------------------------------------------------------- G1
def g1(seed: int, length: int = 100000, L: int = 96, H: int = 24, train_stride: int = 2) -> Task:
    """v1 data and splits; channels reordered so y is last."""
    gen = GTSeries(GTConfig(length=length, seed=seed))
    perm = [c for c in range(len(G1_CHANNELS)) if c != G1_TARGET] + [G1_TARGET]
    raw = gen.data[:, perm]
    n_tr, n_va = int(0.7 * len(raw)), int(0.1 * len(raw))
    mu, sd = raw[:n_tr].mean(0), raw[:n_tr].std(0)
    data = ((raw - mu) / sd).astype(np.float32)
    starts = {"train": np.arange(0, n_tr - L - H + 1, train_stride),
              "val": np.arange(n_tr - L, n_tr + n_va - L - H + 1),
              "test": np.arange(n_tr + n_va - L, len(raw) - L - H + 1)}
    idx = lambda s: s[:, None] + np.arange(L + H)
    X = {k: data[idx(s)][:, :L].transpose(0, 2, 1).copy() for k, s in starts.items()}
    Y = {k: data[idx(s)][:, L:, -1].copy() for k, s in starts.items()}
    oracle = lambda k: float((((gen.oracle_forecast(starts[k], L, H) - mu[-1]) / sd[-1] - Y[k]) ** 2).mean())
    score = gen.score_mask(L)[perm]
    te = starts["test"]
    return Task(name="g1", channels=[G1_CHANNELS[c] for c in perm], L=L, H=H, X=X, Y=Y, score_mask=score,
                gt_cells=lambda i: gen.gt_mask(int(te[i]), L, H)[perm],
                oracle_mse={"val": oracle("val"), "test": oracle("test")},
                meta={"starts": starts, "regime_channel": perm.index(REGIME), "generator": gen.config_dict()})


# ---------------------------------------------------------------- G2
def _gsshap_module():
    spec = importlib.util.spec_from_file_location("gsshap_synthetic",
                                                  GSSHAP_DIR / "scripts" / "synthetic_recovery_experiment.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod                                            # dataclasses look the module up
    sys.path.insert(0, str(GSSHAP_DIR))
    try:
        spec.loader.exec_module(mod)
    finally:
        sys.path.remove(str(GSSHAP_DIR))
    return mod


def g2(setting: str, seed: int) -> Task:
    """
    GS-SHAP setting A/B/C with its default sizes (5000/1000/1000 samples, T 100, D 12).
    Our seed s maps to their seed 42 + s (their default --seed 42, seeds 42, 43, 44).
    """
    gs = _gsshap_module()
    cfg = gs.SyntheticConfig(name=setting)
    b = gs.build_synthetic_bundle(setting, cfg, 42 + seed)
    D, T = cfg.num_features, cfg.seq_len
    X, Y = {}, {}
    for k, split in (("train", b.train), ("val", b.val), ("test", b.test)):
        x = split.X.transpose(0, 2, 1)                                      # [N, D, T]
        X[k] = np.concatenate([x, np.zeros((len(x), 1, T), np.float32)], 1)  # target channel: no past
        Y[k] = (2.0 * split.y - 1.0).astype(np.float32)[:, None]            # label -> +-1
    Xs = _standardise(X, Y, D)[0]                                           # the empty target channel stays 0
    gt = b.test.gt_masks.transpose(0, 2, 1) > 0                              # [N, D, T]
    score = np.ones((D + 1, T), bool)
    score[D] = False
    return Task(name=f"g2{setting.lower()}", channels=[f"f{d}" for d in range(D)] + ["y"], L=T, H=1,
                X=Xs, Y=Y, score_mask=score,
                gt_cells=lambda i: np.concatenate([gt[i], np.zeros((1, T), bool)]),
                oracle_mse={}, meta={"groups": b.true_groups, "segments": b.true_segments,
                                      "gt_players": b.test.gt_players, "setting": setting})


# ---------------------------------------------------------------- G3
G3_FEATURES = ["hourofday", "dayofweek", "month", "holiday", "temperature", "noise1", "noise2"]
G3_GT_KEYS = {"hourofday": "hourofday", "dayofweek": "dayofweek", "month": "month", "holiday": "holiday",
              "temperature": "T", "load": "load"}


def g3(seed: int, n_train: int = 20000) -> Task:
    """
    Channels: the 7 covariates over past + future (L = 336), then load (past, future = 0).
    Training uses n_train samples drawn (by seed) from the official train split; val/test
    are the official dev/test splits, and the explained windows are the 1000 samples of
    test_ground_truth.json (split "gt").

    The explained output is the forecast at ONE horizon step per window (drawn once with
    seed 0, identical for every model and seed), because over the full 168 h horizon the
    hour-of-day and day-of-week effects average out (mean |phi| 0.004 vs 0.08 per step).
    """
    if not SHAPFORMER_NPZ.exists():
        raise FileNotFoundError(f"{SHAPFORMER_NPZ} missing: run python -m scripts.prepare_shapformer")
    z = np.load(SHAPFORMER_NPZ)
    rng = np.random.default_rng(seed)
    raw = {}
    for k, src in (("train", "train"), ("val", "dev"), ("test", "test"), ("gt", "gt")):
        enc, dec, y = z[f"{src}_enc"], z[f"{src}_dec"], z[f"{src}_y"]      # [N, 8, 168], [N, 7, 168], [N, 168]
        if k == "train" and len(y) > n_train:
            keep = np.sort(rng.choice(len(y), n_train, replace=False))
            enc, dec, y = enc[keep], dec[keep], y[keep]
        raw[k] = (np.concatenate([enc[:, 1:], dec], axis=2), enc[:, :1], y)  # covariates [N, 7, 336], past load
    cov_tr, load_tr, _ = raw["train"]
    mu_c, sd_c = cov_tr.mean((0, 2), keepdims=True), cov_tr.std((0, 2), keepdims=True)
    sd_c[sd_c < 1e-8] = 1.0
    mu_l, sd_l = float(load_tr.mean()), float(load_tr.std())                # past load only
    X, Y = {}, {}
    for k, (cov, load, y) in raw.items():
        load = np.concatenate([(load - mu_l) / sd_l, np.zeros_like(load)], axis=2)   # unknown future load = mean
        X[k] = np.concatenate([(cov - mu_c) / sd_c, load], 1).astype(np.float32)
        Y[k] = ((y - mu_l) / sd_l).astype(np.float32)
    Lp, H = load_tr.shape[-1], Y["train"].shape[-1]
    expl = z["gt_expl"] / sd_l                                              # [N, 6, H] in standardised units
    steps = np.random.default_rng(0).integers(0, H, size=len(expl))
    keys = list(z["gt_expl_keys"])
    order = [keys.index(G3_GT_KEYS[c]) if c in G3_GT_KEYS else None for c in G3_FEATURES + ["load"]]
    at = expl[np.arange(len(expl)), :, steps]                               # [N, 6] at the explained step
    gt_feat = np.stack([at[:, j] if j is not None else np.zeros(len(expl)) for j in order], 1)
    score = np.ones((len(order), 2 * Lp), bool)
    score[-1, Lp:] = False
    clean = (z["gt_base"][:, Lp:] + z["gt_expl"].sum(1) - mu_l) / sd_l     # the generator without its noise
    return Task(name="g3", channels=G3_FEATURES + ["load"], L=2 * Lp, H=H, X=X, Y=Y,
                score_mask=score, gt_feat=lambda i: gt_feat[i], explain_steps=lambda i: steps[i:i + 1],
                explain_split="gt", oracle_mse={"gt": float(((clean - Y["gt"]) ** 2).mean())},
                meta={"past_len": Lp, "load_mu": mu_l, "load_sd": sd_l})


# ---------------------------------------------------------------- public (phase 2)
PUBLIC = {"etth1": ("ETT-small/ETTh1.csv", "ETTh"), "weather": ("weather/weather.csv", "custom"),
          # v2.1 replication (plan §12), chosen and checked for sentinels before any of their results
          "etth2": ("ETT-small/ETTh2.csv", "ETTh"), "ettm1": ("ETT-small/ETTm1.csv", "ETTm"),
          "exchange": ("exchange_rate/exchange_rate.csv", "custom")}


def public(name: str, L: int = 96, H: int = 96) -> Task:
    csv, split_type = PUBLIC[name]
    df = pd.read_csv(ROOT / "dataset" / csv).drop(columns="date")                        # OT is the last column
    # Weather has -9999 sentinels (80 train rows, 50 in OT) that inflate the train sd of OT from 18 to 384;
    # interpolate them before standardising (plan §12, pre-results data change)
    raw = df.mask(df <= -9990).interpolate(limit_direction="both").to_numpy(np.float32)
    b1, b2 = _compute_borders(split_type, len(raw), L)
    mu, sd = raw[b1[0]:b2[0]].mean(0), raw[b1[0]:b2[0]].std(0)
    data = (raw - mu) / np.where(sd < 1e-8, 1.0, sd)
    X, Y = {}, {}
    for k, lo, hi in zip(("train", "val", "test"), b1, b2):
        s = np.arange(lo, hi - L - H + 1)
        w = data[s[:, None] + np.arange(L + H)]
        X[k], Y[k] = w[:, :L].transpose(0, 2, 1).copy(), w[:, L:, -1].copy()
    cols = list(pd.read_csv(ROOT / "dataset" / csv, nrows=0).columns[1:])
    return Task(name=name, channels=cols, L=L, H=H, X=X, Y=Y, score_mask=np.ones((len(cols), L), bool), norm=True)


# v2.2 horizon robustness (plan §12): same data and L, longer horizons
HORIZON = [f"{d}_h{h}" for d in ("etth1", "weather") for h in (192, 336, 720)]
TASKS = ["g1", "g2a", "g2b", "g2c", "g3", *PUBLIC, *HORIZON]


def build_task(name: str, seed: int) -> Task:
    if name == "g1":
        return g1(seed)
    if name in ("g2a", "g2b", "g2c"):
        return g2(name[-1].upper(), seed)
    if name == "g3":
        return g3(seed)
    if name in PUBLIC:
        return public(name)
    if name in HORIZON:
        base, h = name.rsplit("_h", 1)
        t = public(base, H=int(h))
        t.name = name
        return t
    raise ValueError(f"unknown task {name!r}")
